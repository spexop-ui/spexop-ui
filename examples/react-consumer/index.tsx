import assert from 'node:assert/strict';
import { renderToStaticMarkup } from 'react-dom/server';
import { createTheme, generateCSS, generateTailwind, generateDTCG, readDTCG, auditThemeAccessibility, resolveTheme } from '@spexop/theme';
import { fixture } from './fixture.js';
const theme = createTheme(fixture());
const css = generateCSS(theme);
const markup = renderToStaticMarkup(<main data-theme="dark"><style>{css}</style><p style={{color:'var(--theme-text)',background:'var(--theme-surface)'}}>Spexop Theme consumer</p></main>);
assert(markup.includes('data-theme="dark"'));
assert(markup.includes('Spexop Theme consumer'));
assert(css.includes('--theme-primary: oklch('));
assert.equal(resolveTheme(theme,'dark').colors.textSecondary, '#fff');
assert(readDTCG(generateDTCG(theme)).dark);
assert(generateTailwind(theme).includes('@theme inline'));
const audit=auditThemeAccessibility(theme);
assert.equal(audit.passed,true);
assert.equal(audit.summary.notEvaluated,0);
const broken=fixture();broken.colors.text='{colors.absent}';
assert.throws(()=>generateCSS(broken));
const low=fixture();low.colors.text='#ddd';assert.equal(auditThemeAccessibility(low).passed,false);
console.log(JSON.stringify({consumer:'React 19 / TypeScript 5.9 / isolated packed ESM',node:process.version,import:true,serverRender:true,lightDark:true,dtcg:true,css:true,tailwind:true,contrast:true,negativeChecks:true,renderedBytes:markup.length}));
